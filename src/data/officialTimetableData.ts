// Helper to construct a slot with 20 classes cleanly
function makeSlot(
  day: DayOfWeek,
  dayName: string,
  session: "Sáng" | "Chiều",
  period: number,
  assignments: Record<string, [string, string]>
): TimetableSlot {
  const classSubjectMap: Record<string, { subject: string; teacherName: string }> = {};
  for (const [cls, [subject, teacherName]] of Object.entries(assignments)) {
    classSubjectMap[cls] = { subject, teacherName };
  }
  return {
    day,
    dayName,
    session,
    period,
    classSubjectMap,
  };
}

